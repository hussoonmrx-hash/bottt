def build_message():
    now = datetime.now()
    is_friday = now.weekday() == 4  # Friday is 4 (Monday=0)

    if is_friday:
        text = random.choice(FRIDAY_DUA_LIST)
        title = CATEGORY_TITLES["friday"]
    else:
        category = random.choice(["dua", "azkar", "verse", "prayer", "lesson"])

        if category == "dua":
            text = random.choice(DUA_LIST)
        elif category == "azkar":
            text = random.choice(AZKAR_LIST)
        elif category == "verse":
            text = random.choice(QURAN_VERSES)
        elif category == "prayer":
            text = random.choice(PRAYER_REMINDERS)
        else:
            text = random.choice(MORAL_LESSONS)

        title = CATEGORY_TITLES[category]

    embed = discord.Embed(
        description=text,
        color=0x2B2D31,
        timestamp=datetime.utcnow()
    )
    embed.set_footer(text=title)

    return embed


class Azkar(commands.Cog):
    def __init__(self, bot):
        self.bot = bot
        self.azkar_task.start()

    def cog_unload(self):
        self.azkar_task.cancel()

    @tasks.loop(time=time(hour=8, minute=0))  # Run daily at 8:00 AM
    async def azkar_task(self):
        channel = self.bot.get_channel(DUA_CHANNEL_ID)
        if channel:
            embed = build_message()
            try:
                await channel.send(embed=embed)
                print(f"[Azkar] Sent daily message to channel {DUA_CHANNEL_ID}")
            except Exception as e:
                print(f"[Azkar] Error sending message: {e}")

    @azkar_task.before_loop
    async def before_azkar(self):
        await self.bot.wait_until_ready()


async def setup(bot):
    await bot.add_cog(Azkar(bot))
